const {runSuite} = require('../tests/support/browser_qa.cjs');

runSuite('reader-features',async ({page,api,url,check,shot,upload,eventually,assert,details}) => {
  const chapters = Array.from({length:14},(_,i) => {
    const title = `第${i+1}章 ${i===2?'寻找散落在旧城河岸边的长标题来信':'原创章节'+(i+1)}`;
    const body = Array.from({length:i===0?75:18},(_,p) => `这是第${i+1}章第${p+1}段原创正文。雨夜的旧城很安静，主人公沿着河岸寻找来信的线索。`).join('\n\n');
    const extra = i===0?'':`\n\nneedle needle needle needle\n\n  📚<script>🧪目标</script> literal % _ \\ 在第${i+1}章。`;
    return title+'\n'+body+extra;
  });
  const book = await upload('河岸来信与很长的原创验收书名.txt',chapters.join('\n\n'));
  const other = await upload('另一部原创书.txt','第1章 另一部书\nOTHER_BOOK_SENTINEL\n第2章 继续\n另一本书的独立内容。');
  let sequence=0;
  const gotoReader = async (id,chapter=1) => {
    await page.goto(`${url}/?reader-case=${++sequence}#page=reader&novel=${id}&chapter=${chapter}`);
    await page.locator('[data-chapter-title]').waitFor();
    await eventually(async () => await page.locator(`.r-directory [data-chapter="${chapter}"]`).getAttribute('aria-current')==='true','chapter selected');
  };
  await gotoReader(book.novel_id);
  const cacheChecks = await page.evaluate(async () => {
    const {createChapterLoader} = await import('/reader-data.js');
    const ok = (value,label) => {if(!value) throw new Error(label);};
    const labels=[];
    const calls=[];
    let loader=createChapterLoader(async index => {calls.push(index);return {content:'body-'+index};});
    for(const index of [1,2,3,4,1,5,2]) await loader.get(index);
    ok(calls.join(',')==='1,2,3,4,5,2','default count LRU');loader.dispose();labels.push('fulfilled LRU count');
    const large=[];
    loader=createChapterLoader(async index => {large.push(index);return {content:'x'.repeat(index===9?300001:80000)};});
    for(const index of [1,2,3,4,1,9,9]) await loader.get(index);
    ok(large.join(',')==='1,2,3,4,1,9,9','character cap and oversized item');loader.dispose();labels.push('character cap and oversized no-cache');
    const pending=[];
    loader=createChapterLoader((index,{signal}) => new Promise((resolve,reject)=>pending.push({index,signal,resolve,reject})));
    const first=loader.get(1);first.catch(()=>{});await Promise.resolve();
    ok(first===loader.get(1),'dedupe same request');
    await loader.prefetch(2);ok(pending.length===1,'only one pending prefetch');
    const second=loader.get(2);await Promise.resolve();ok(pending[0].signal.aborted,'cancel superseded');
    pending[1].resolve({content:'new'});await second;
    pending[0].resolve({content:'stale'});ok(await first.then(()=>false,e=>e.name==='AbortError'),'ignore late completion');
    const again=loader.get(1);again.catch(()=>{});await Promise.resolve();ok(pending.length===3,'stale did not cache');
    loader.dispose();ok(pending[2].signal.aborted,'dispose aborts');pending[2].resolve({content:'late-disposed'});
    ok(await again.then(()=>false,e=>e.name==='AbortError'),'dispose rejects late data');
    ok(await loader.get(2).then(()=>false,e=>e.name==='AbortError'),'dispose clears previous cached data');
    labels.push('pending dedupe cancellation stale completion disposal');
    let attempts=0;
    loader=createChapterLoader(async()=>{if(++attempts===1)throw new Error('expected prefetch failure');return {content:'retry'};});
    await loader.prefetch(1);ok((await loader.get(1)).content==='retry'&&attempts===2,'prefetch failure not cached');
    loader.dispose();labels.push('failed prefetch retries foreground');
    return labels;
  });
  details.cacheChecks=cacheChecks;
  check('生产loader默认LRU/字符上限、在途去重、取消、失败重试与销毁隔离');

  const bodies=[];
  page.on('request',request => {const m=new URL(request.url()).pathname.match(/\/novels\/(\d+)\/chapters\/(\d+)$/);if(m)bodies.push([Number(m[1]),Number(m[2])]);});
  await gotoReader(book.novel_id);
  await eventually(() => bodies.some(([id,ch])=>id===book.novel_id&&ch===2),'next prefetched');
  assert.deepEqual([...new Set(bodies.filter(([id])=>id===book.novel_id).map(([,ch])=>ch))].sort(),[1,2]);
  const before=bodies.length;
  await page.getByRole('button',{name:'下一章',exact:true}).click();
  await eventually(async()=>await page.locator('[data-chapter="2"]').getAttribute('aria-current')==='true','next visible');
  assert(!bodies.slice(before).some(([id,ch])=>id===book.novel_id&&ch===2));
  check('真实阅读只预读下一章，命中预读时不重复请求');

  await gotoReader(book.novel_id);
  await page.locator('.r-scroll').evaluate(node=>{node.scrollTop=1500;});
  await eventually(async()=> (await api(`/novels/${book.novel_id}/reading`)).position.paragraph>0,'original position saved');
  const origin=(await api(`/novels/${book.novel_id}/reading`)).position;
  const searchRequests=[];
  page.on('request',request=>{const u=new URL(request.url());if(u.pathname.endsWith('/search'))searchRequests.push(u.searchParams.get('q'));});
  await page.getByRole('button',{name:'搜索全文',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'搜索全文'});
  const input=()=>dialog.getByRole('searchbox',{name:'在全书正文中搜索'});
  await input().fill('ignored-fast-input');await input().fill('needle');
  await eventually(async()=>await dialog.locator('.search-hit').count()===20,'first search page');
  assert.deepEqual(searchRequests,['needle']);
  await dialog.getByRole('button',{name:'更多结果',exact:true}).click();
  await eventually(async()=>await dialog.locator('.search-hit').count()===39,'second search page');
  assert.equal(await dialog.locator('.search-hit script').count(),0);
  check('输入节流只发最终查询，跨章分页39处且每章有界');
  await input().fill('🧪目标');await input().press('Enter');
  await eventually(async()=>await dialog.locator('.search-hit').count()===13,'unicode results');
  assert.equal(await dialog.locator('.search-hit script').count(),0);
  const apiHit=(await api(`/novels/${book.novel_id}/search?q=${encodeURIComponent('🧪目标')}`)).items[0];
  assert(await dialog.locator('.search-hit').first().innerText().then(text=>text.includes('<script>')));
  await shot('search-results-utf16');
  await dialog.locator('.search-hit').first().click();await dialog.waitFor({state:'detached'});
  await page.getByRole('button',{name:'返回搜索前位置',exact:true}).waitFor();
  const highlight=await page.evaluate(()=>{
    const entry=CSS.highlights.get('novelmind-search-hit');
    const range=[...entry][0];
    return {text:range.toString(),offset:range.startOffset,paragraph:Number(range.startContainer.parentElement.dataset.paragraph)};
  });
  assert.deepEqual(highlight,{text:'🧪目标',offset:apiHit.offset,paragraph:apiHit.paragraph});
  await shot('exact-source-hit');
  await page.getByRole('button',{name:'返回搜索前位置',exact:true}).click();
  await eventually(async()=>JSON.stringify((await api(`/novels/${book.novel_id}/reading`)).position)===JSON.stringify(origin),'origin anchor restored');
  check('特殊HTML纯文本，emoji精确UTF16高亮，返回搜索前章段偏移');

  let release,enteredResolve;
  const held=new Promise(resolve=>{release=resolve;});
  const entered=new Promise(resolve=>{enteredResolve=resolve;});
  let aborted=false;
  page.on('requestfailed',request=>{if(request.url().includes('q=slow-fixture'))aborted=true;});
  await page.route('**/search?**',async route=>{
    if(new URL(route.request().url()).searchParams.get('q')!=='slow-fixture') return route.continue();
    enteredResolve();await held;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({items:[{...apiHit,snippet:'STALE_SHOULD_NOT_RENDER',snippet_match_start:0,snippet_match_length:5}],next_offset:null,has_more:false,per_chapter_limit:3})}).catch(()=>{});
  });
  await page.getByRole('button',{name:'搜索全文',exact:true}).click();dialog=page.getByRole('dialog',{name:'搜索全文'});
  await input().fill('slow-fixture');await input().press('Enter');await entered;
  await input().fill('needle');await input().press('Enter');
  await eventually(async()=>await dialog.locator('.search-hit').count()===20,'latest search');
  release();await page.waitForTimeout(180);
  assert(aborted);assert(!await dialog.innerText().then(text=>text.includes('STALE_SHOULD_NOT_RENDER')));
  await dialog.getByRole('button',{name:'关闭',exact:true}).click();await dialog.waitFor({state:'detached'});
  await page.unroute('**/search?**');
  check('取消旧查询，迟到响应不覆盖新结果');

  let releaseChapter, chapterStarted;
  const heldChapter=new Promise(resolve=>{releaseChapter=resolve;});
  const chapterEntered=new Promise(resolve=>{chapterStarted=resolve;});
  const oldChapter=await api(`/novels/${book.novel_id}/chapters/8`);
  await page.route(`**/api/novels/${book.novel_id}/chapters/8`,async route=>{
    chapterStarted();await heldChapter;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(oldChapter)}).catch(()=>{});
  },{times:1});
  await page.locator('[data-chapter="8"]').click();await chapterEntered;
  await page.locator('[data-chapter="10"]').click();
  await eventually(async()=>await page.locator('[data-chapter="10"]').getAttribute('aria-current')==='true','latest chapter');
  releaseChapter();await page.waitForTimeout(120);
  assert.equal(await page.locator('[data-chapter-title]').textContent(),'第10章 原创章节10');
  await eventually(async()=>(await api(`/novels/${book.novel_id}/reading`)).position.chapter===10,'latest position');
  check('快速切章的迟到正文不覆盖最新画面或阅读位置');
  const prefetchFailure=page.waitForResponse(response=>response.url().endsWith(`/novels/${book.novel_id}/chapters/6`)&&response.status()===503);
  await page.route(`**/api/novels/${book.novel_id}/chapters/6`,route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'isolated prefetch failure'})}),{times:1});
  await page.locator('[data-chapter="5"]').click();await prefetchFailure;
  assert.equal(await page.locator('[data-chapter-title]').textContent(),'第5章 原创章节5');
  assert(!await page.locator('[data-paragraphs]').innerText().then(text=>text.includes('isolated prefetch failure')));
  await page.locator('[data-chapter="6"]').click();
  await eventually(async()=>await page.locator('[data-chapter="6"]').getAttribute('aria-current')==='true','failed prefetch foreground retry');
  check('下一章预读失败不破坏当前章，前台进入可重新请求');

  // Seed legacy state on a fresh book, never behind an active reader that autosaves.
  const bookmarkBook=await upload('旧书签兼容原创书.txt',chapters.join('\n\n'));
  const state=await api(`/novels/${bookmarkBook.novel_id}/reading`);
  state.bookmarks=[{id:'legacy-fixture',chapter:1,paragraph:1,offset:0,snippet:'旧书签原摘录'}];
  await api(`/novels/${bookmarkBook.novel_id}/reading`,{method:'PUT',data:state});
  await gotoReader(bookmarkBook.novel_id);
  await page.getByRole('tab',{name:/书签/}).click();
  await page.getByRole('button',{name:'编辑第 1 章书签'}).click();
  dialog=page.getByRole('dialog',{name:'编辑书签'});
  await dialog.getByLabel('书签名称',{exact:true}).fill('  河岸的线索📚 <b>纯文本</b>  ');
  await dialog.getByLabel('书签备注',{exact:true}).fill('  自编备注与关键词  ');
  await shot('bookmark-editor');
  await dialog.getByRole('button',{name:'保存书签',exact:true}).click();await dialog.waitFor({state:'detached'});
  await eventually(async()=>(await api(`/novels/${bookmarkBook.novel_id}/reading`)).bookmarks[0].label==='河岸的线索📚 <b>纯文本</b>','bookmark persisted');
  let bookmark=(await api(`/novels/${bookmarkBook.novel_id}/reading`)).bookmarks[0];
  assert.equal(bookmark.id,'legacy-fixture');assert.equal(bookmark.snippet,'旧书签原摘录');assert.equal(bookmark.note,'自编备注与关键词');
  assert.equal(await page.locator('.r-bookmark-entry b').count(),0);
  await page.getByRole('searchbox',{name:'搜索书签',exact:true}).fill('关键词');
  assert.equal(await page.locator('.r-bookmark-entry').count(),1);
  await page.reload();await page.locator('[data-chapter-title]').waitFor();
  await page.getByRole('tab',{name:/书签/}).click();
  assert(await page.locator('.r-bookmark-entry').innerText().then(text=>text.includes('河岸的线索')));
  await shot('bookmark-named');
  await page.getByRole('button',{name:'删除第 1 章书签'}).click();
  await eventually(async()=>(await api(`/novels/${bookmarkBook.novel_id}/reading`)).bookmarks.length===0,'bookmark delete');
  check('旧书签命名/备注/过滤/刷新/删除，不改ID摘录锚点且HTML安全');

  await gotoReader(other.novel_id);
  await page.getByText('OTHER_BOOK_SENTINEL',{exact:true}).waitFor();
  assert(!await page.locator('[data-paragraphs]').innerText().then(text=>text.includes('河岸寻找')));
  await page.getByRole('button',{name:'返回资料库',exact:true}).click();
  await page.getByRole('heading',{name:'你的资料库',exact:true}).waitFor();
  await page.keyboard.press('Control+Shift+f');await page.waitForTimeout(100);
  assert.equal(await page.getByRole('dialog',{name:'搜索全文'}).count(),0);
  assert.deepEqual(await api('/workspace/tasks'),[]);
  check('跨书缓存隔离、离开阅读器移除快捷键、无模型任务');
  details.originalPosition=origin;details.highlight=highlight;details.chapterRequests=bodies;
}, {reducedMotion:'reduce'}).catch(error=>{console.error(error);process.exitCode=1;});
