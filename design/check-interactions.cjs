const { chromium }=require('playwright');
const assert=require('node:assert/strict');
const fs=require('fs');
const path=require('path');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  await page.goto('http://127.0.0.1:8768/GXXh7.html');
  await page.evaluate(()=>document.fonts.ready);
  await page.getByRole('dialog',{name:'欢迎来到 NovelMind'}).waitFor();
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished)));
  await page.screenshot({path:path.join(__dirname,'exports','first-run.png')});
  await page.getByRole('button',{name:'同意并开始',exact:true}).click();
  await page.reload();
  assert.equal(await page.locator('.nm-privacy').count(),0);
  assert.equal(await page.locator('[data-pencil-name="窗口控制"]').count(),0);
  await page.getByRole('button',{name:'调整阅读字号'}).click();
  const dialog=page.getByRole('dialog',{name:'阅读外观'});
  await dialog.waitFor();
  await dialog.locator('input').fill('20');
  assert.equal(await dialog.locator('output').textContent(),'20 px');
  await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished)));
  await page.screenshot({path:path.join(__dirname,'exports','reading-interaction.png')});
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(),0);
  await page.getByRole('button',{name:'原文问答',exact:true}).click();
  await page.getByRole('textbox',{name:'问题',exact:true}).waitFor();
  const submit=page.locator('[data-pencil-name="提交问题 ↑"][role="button"]');
  assert.equal(await submit.getAttribute('aria-disabled'),'true');
  await page.getByRole('textbox',{name:'问题',exact:true}).fill('林舟为什么留下？');
  assert.equal(await page.locator('.nm-check').count(),0);
  assert.equal(await submit.getAttribute('aria-disabled'),'false');
  await submit.click();
  await page.getByRole('status').waitFor();
  assert.match(await page.getByRole('status').textContent(),/不发送模型请求/);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await submit.evaluate(e=>getComputedStyle(e).transitionDuration),'0s');
  const material=await page.locator('[data-pencil-name="半透明分段导航"]').evaluate(e=>({blur:getComputedStyle(e).backdropFilter,fill:getComputedStyle(e).backgroundColor}));
  assert.match(material.blur,/24px/);assert.match(material.fill,/rgba/);
  await page.goto('http://127.0.0.1:8768/index.html?v=3');
  await page.getByRole('button',{name:'正文阅读',exact:true}).click();
  await page.frameLocator('iframe').getByRole('button',{name:'调整阅读字号'}).waitFor();
  await page.frameLocator('iframe').getByRole('button',{name:'原文问答',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('nav button')].find(e=>e.textContent==='原文问答').getAttribute('aria-pressed')==='true');
  await page.goto('http://127.0.0.1:8768/ElfMF.html');
  assert.equal(await page.locator('.nm-privacy').count(),0);
  await page.getByRole('button',{name:/隐私与外部处理/}).click();
  await page.getByRole('button',{name:'仅使用本地阅读',exact:true}).click();
  await page.goto('http://127.0.0.1:8768/V9YZY.html');
  assert.equal(await page.locator('.nm-privacy').count(),0);
  await page.getByRole('textbox',{name:'问题',exact:true}).fill('林舟为什么留下？');
  assert.equal(await page.locator('[data-pencil-name="提交问题 ↑"][role="button"]').getAttribute('aria-disabled'),'true');
  await page.goto('http://127.0.0.1:8768/ElfMF.html');
  await page.getByRole('button',{name:/隐私与外部处理/}).click();
  await page.getByRole('button',{name:'同意并开始',exact:true}).click();
  await page.goto('http://127.0.0.1:8768/V9YZY.html');
  await page.getByRole('textbox',{name:'问题',exact:true}).fill('林舟为什么留下？');
  assert.equal(await page.locator('[data-pencil-name="提交问题 ↑"][role="button"]').getAttribute('aria-disabled'),'false');
  fs.writeFileSync(path.join(__dirname,'interaction-qa.json'),JSON.stringify({passed:true,checks:['first run dialog','choice persists after reload','no repeated prompt during navigation','no inline consent checkboxes','settings revoke and re-enable','local mode blocks AI actions','no window controls','reading popover','font size adjustment','escape dismiss','in-app navigation','preview-only submit','reduced motion','translucent background blur','gallery navigation sync'],material},null,2));
  console.log('15 interaction checks passed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
